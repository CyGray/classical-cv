def variant_tier_dl41(name: str) -> str:
    """Tier ('light'/'medium'/'heavy') for one DL-41 modification name -
    looked up directly from ``DL41_CATEGORY_TIER`` (the DL team's explicit
    mapping), NOT the legacy severity-ranking heuristic in
    ``scripts/reporting/generate_robustness_report.py``."""
    tier = DL41_TIER_MAP.get(name)
    if tier is None:
        raise ValueError(f"Unknown DL-41 modification {name!r}. Valid: {sorted(DL41_TIER_MAP)}")
    return tier


def get_modification_set(mod_set: str) -> tuple[list[tuple[str, object, list]], int]:
    """(modifications, variant_count) for ``--mod-set {legacy,dl41}``."""
    if mod_set == "legacy":
        return MODIFICATIONS, VARIANT_COUNT
    if mod_set == "dl41":
        return DL41_MODIFICATIONS, DL41_VARIANT_COUNT
    raise ValueError(f"Unknown mod_set {mod_set!r}. Valid: 'legacy', 'dl41'.")


def parse_variant(spec: str) -> tuple[str, float]:
    """Parse "name:level" (e.g. "motion_blur:5", "contrast_down:0.55",
    "rotation:-10") into the exact (name, level) pair from ``MODIFICATIONS`` -
    the returned level is the SAME object (int stays int, float stays float),
    not a freshly-parsed value, so it hashes/compares identically to the
    MODIFICATIONS entry. Raises ValueError listing valid variants on any
    mismatch."""
    name, sep, level_str = spec.partition(":")
    if not sep:
        raise ValueError(
            f"Invalid variant spec {spec!r} (expected 'name:level'). "
            f"Valid variants: {_ALL_VARIANT_SPECS}"
        )
    levels = _LEVELS_BY_NAME.get(name)
    if levels is None:
        raise ValueError(
            f"Unknown modification {name!r} in {spec!r}. Valid variants: {_ALL_VARIANT_SPECS}"
        )
    try:
        parsed = float(level_str)
    except ValueError:
        raise ValueError(
            f"Non-numeric level in {spec!r}. Valid variants: {_ALL_VARIANT_SPECS}"
        ) from None
    for level in levels:
        if float(level) == parsed:
            return name, level
    raise ValueError(
        f"Unknown level {level_str!r} for modification {name!r} in {spec!r}. "
        f"Valid variants: {_ALL_VARIANT_SPECS}"
    )
