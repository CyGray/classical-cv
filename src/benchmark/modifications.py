"""The shared 41-variant modification suite (12 types x levels = 41 variants).

Single source of truth for the DB2-style modified-image benchmark, used by:

* ``src/benchmark/accuracy_ratio.py``        - classical families (LBPH/Eigen/Fisher)
* ``src/benchmark/accuracy_ratio_hybrid.py`` - LBPH vs SFace vs hybrid cascade

Every transform takes ``(gray_or_bgr_image, level, rng)`` and returns the same
shape/dtype. Noise/occlusion consume the rng; deterministic transforms ignore
it. Seed via :func:`stable_rng` per (image, modification, level) so any script
that applies the suite produces the *identical* modified probe - that is what
makes cross-family AR numbers comparable.

NOTE: the official 41-modification list from the team spec sheet should be
confirmed; this suite is the documented stand-in (the counts match: 41
variants/original, La Salle DB2 = 280 x 41 = 11,480 when train originals are
included).
"""

from __future__ import annotations

import math
import zlib

import cv2 as cv
import numpy as np


def _u8(image: np.ndarray) -> np.ndarray:
    return np.clip(image, 0, 255).astype(np.uint8)


def _brightness(img: np.ndarray, offset: float, _rng) -> np.ndarray:
    return _u8(img.astype(np.float32) + offset)


def _contrast(img: np.ndarray, factor: float, _rng) -> np.ndarray:
    return _u8((img.astype(np.float32) - 128.0) * factor + 128.0)


def _gamma(img: np.ndarray, gamma: float, _rng) -> np.ndarray:
    table = _u8(((np.arange(256, dtype=np.float32) / 255.0) ** (1.0 / max(gamma, 1e-6))) * 255.0)
    return cv.LUT(img, table)


def _gaussian_noise(img: np.ndarray, sigma: float, rng: np.random.Generator) -> np.ndarray:
    return _u8(img.astype(np.float32) + rng.normal(0.0, sigma, img.shape).astype(np.float32))


def _gaussian_blur(img: np.ndarray, ksize: int, _rng) -> np.ndarray:
    k = int(ksize) | 1
    return cv.GaussianBlur(img, (k, k), 0)


def _motion_blur(img: np.ndarray, ksize: int, _rng) -> np.ndarray:
    k = max(3, int(ksize) | 1)
    kernel = np.zeros((k, k), dtype=np.float32)
    kernel[k // 2, :] = 1.0 / float(k)
    return cv.filter2D(img, -1, kernel)


def _rotation(img: np.ndarray, angle_deg: float, _rng) -> np.ndarray:
    h, w = img.shape[:2]
    matrix = cv.getRotationMatrix2D(((w - 1) / 2.0, (h - 1) / 2.0), angle_deg, 1.0)
    return cv.warpAffine(img, matrix, (w, h), flags=cv.INTER_LINEAR,
                         borderMode=cv.BORDER_REFLECT_101)


def _zoom(img: np.ndarray, zoom: float, _rng) -> np.ndarray:
    h, w = img.shape[:2]
    matrix = cv.getRotationMatrix2D(((w - 1) / 2.0, (h - 1) / 2.0), 0.0, zoom)
    return cv.warpAffine(img, matrix, (w, h), flags=cv.INTER_LINEAR,
                         borderMode=cv.BORDER_REFLECT_101)


def _occlusion(img: np.ndarray, area_fraction: float, rng: np.random.Generator) -> np.ndarray:
    h, w = img.shape[:2]
    target = max(1.0, area_fraction * h * w)
    rect_h = int(max(4, round(math.sqrt(target))))
    rect_w = int(max(4, round(target / rect_h)))
    rect_h, rect_w = min(rect_h, h), min(rect_w, w)
    y0 = int(rng.integers(0, max(1, h - rect_h + 1)))
    x0 = int(rng.integers(0, max(1, w - rect_w + 1)))
    out = img.copy()
    patch = out[y0: y0 + rect_h, x0: x0 + rect_w]
    fill = int(np.median(patch)) if patch.size else 128
    out[y0: y0 + rect_h, x0: x0 + rect_w] = _u8(
        0.55 * patch.astype(np.float32) + 0.45 * fill
    )
    return out


# --------------------------------------------------------------------------- #
# DL-41 taxonomy transforms (src/benchmark/modifications.py `--mod-set dl41`).
#
# These mirror the modification NAMES/tiers verbatim from the DL team's
# ``MODIFICATION_MAPS`` in ``..\deep-learning\ar-table.py`` (lines 15-57) so
# the CV and DL AR tables are directly comparable. ar-table.py only records
# category+tier per suffix, not the pixel-level implementation (the images it
# scores were generated by a separate DL-side pipeline not present in this
# repo) - the actual transform math below is this repo's own, reasonable-best
# implementation of what each name conventionally means; only the NAMES and
# TIERS are pinned to the DL spec, not necessarily bit-identical pixel output.
#
# Unlike the legacy family+levels shape (12 families x [levels] = 41 rows),
# the DL-41 taxonomy is 41 already-distinct named modifications with no
# shared numeric "level" knob within a name, so each entry below carries a
# single-element level list. ``stable_rng`` still keys on (mod_name, level),
# so RNG determinism/shard-safety is unaffected - level is just an
# informational placeholder (the literal parsed severity value) for the
# genuinely single-level entries.
#
# These operate on either a 2D gray tile or a 3D BGR color tile (checked via
# ``img.ndim``), because color-only transforms (monochrome, color_8bit,
# rgb565) are meaningless on an already-grayscale tile - callers using the
# dl41 set must keep the color image through modification and only convert
# to gray afterward (see accuracy_ratio_hybrid.py's ``--mod-set dl41`` path).
# --------------------------------------------------------------------------- #

def _is_color(img: np.ndarray) -> bool:
    return img.ndim == 3 and img.shape[2] == 3


def _brightness_pct(img: np.ndarray, pct: float, _rng) -> np.ndarray:
    """Multiplicative brightness gain of pct% (brightness_pXX)."""
    return _u8(img.astype(np.float32) * (1.0 + pct / 100.0))


def _monochrome(img: np.ndarray, _level, _rng) -> np.ndarray:
    """Colour -> monochrome. No-op (documented) if the tile is already gray."""
    if not _is_color(img):
        return img
    gray = cv.cvtColor(img, cv.COLOR_BGR2GRAY)
    return cv.cvtColor(gray, cv.COLOR_GRAY2BGR)


def _jpeg_compress(img: np.ndarray, quality: float, _rng) -> np.ndarray:
    """JPEG re-encode/decode round-trip at the given quality (jpeg_qXX)."""
    ok, enc = cv.imencode(".jpg", img, [int(cv.IMWRITE_JPEG_QUALITY), int(quality)])
    if not ok:
        return img
    flag = cv.IMREAD_COLOR if _is_color(img) else cv.IMREAD_GRAYSCALE
    dec = cv.imdecode(enc, flag)
    return dec if dec is not None else img


def _color_reduce(img: np.ndarray, bits: tuple[int, int, int], _rng) -> np.ndarray:
    """Quantize each channel to ``bits[c]`` bits, then rescale back to 0-255
    (color_8bit ~ 3-3-2 bpp, rgb565 ~ 5-6-5 bpp). No-op on a gray tile."""
    if not _is_color(img):
        return img
    out = img.astype(np.float32)
    for c, b in enumerate(bits):
        levels = max(2, 2 ** b)
        step = 255.0 / (levels - 1)
        out[..., c] = np.round(out[..., c] / step) * step
    return _u8(out)


def _histeq(img: np.ndarray, _level, _rng) -> np.ndarray:
    """Histogram equalization (luminance channel only for color)."""
    if not _is_color(img):
        return cv.equalizeHist(img)
    ycrcb = cv.cvtColor(img, cv.COLOR_BGR2YCrCb)
    ycrcb[..., 0] = cv.equalizeHist(ycrcb[..., 0])
    return cv.cvtColor(ycrcb, cv.COLOR_YCrCb2BGR)


def _autolevel(img: np.ndarray, _level, _rng) -> np.ndarray:
    """Per-channel linear contrast stretch (0.5/99.5 percentile -> 0/255)."""
    channels = cv.split(img) if _is_color(img) else [img]
    out_channels = []
    for ch in channels:
        lo, hi = np.percentile(ch, [0.5, 99.5])
        if hi <= lo:
            out_channels.append(ch)
            continue
        stretched = (ch.astype(np.float32) - lo) * (255.0 / (hi - lo))
        out_channels.append(_u8(stretched))
    return cv.merge(out_channels) if _is_color(img) else out_channels[0]


def _canonical_rotate(img: np.ndarray, angle_deg: float, _rng) -> np.ndarray:
    """Lossless 90/180/270 rotation (rot_90/180/270) - detector-canonical
    tier, reported separately, never averaged into the headline AR mean."""
    code = {90: cv.ROTATE_90_CLOCKWISE, 180: cv.ROTATE_180, 270: cv.ROTATE_90_COUNTERCLOCKWISE}[int(angle_deg)]
    return cv.rotate(img, code)


def _simple_rotate(img: np.ndarray, angle_deg: float, _rng) -> np.ndarray:
    """Small-angle rotation (rot_10/25/45) - reuses the legacy warpAffine path."""
    return _rotation(img, angle_deg, _rng)


def _scale(img: np.ndarray, pct: float, _rng) -> np.ndarray:
    """Zoom by pct% (scale_50/70/90) - reuses the legacy zoom warpAffine path."""
    return _zoom(img, pct / 100.0, _rng)


def _translate(img: np.ndarray, pct: float, _rng) -> np.ndarray:
    """Diagonal shift by pct% of min(h, w) (trans_10/20/30), deterministic."""
    h, w = img.shape[:2]
    shift = (pct / 100.0) * min(h, w)
    matrix = np.array([[1, 0, shift], [0, 1, shift]], dtype=np.float32)
    return cv.warpAffine(img, matrix, (w, h), flags=cv.INTER_LINEAR,
                         borderMode=cv.BORDER_REFLECT_101)


def _flip_lr(img: np.ndarray, _level, _rng) -> np.ndarray:
    """Horizontal mirror (flip_lr) - detector-canonical tier (see module docstring)."""
    return cv.flip(img, 1)


def _aspect_change(img: np.ndarray, ratio: float, _rng) -> np.ndarray:
    """Squash to the target width:height ratio then stretch back to the
    original frame size (aspect_16_9 ~= 1.778, aspect_6_3 = 2.0)."""
    h, w = img.shape[:2]
    squashed_h = max(1, int(round(w / ratio)))
    squashed = cv.resize(img, (w, squashed_h), interpolation=cv.INTER_AREA)
    return cv.resize(squashed, (w, h), interpolation=cv.INTER_LINEAR)


def _crop_resize(img: np.ndarray, keep_pct: float, _rng) -> np.ndarray:
    """Centered crop retaining keep_pct% of area, resized back up (crop_60/70/90)."""
    h, w = img.shape[:2]
    frac = math.sqrt(keep_pct / 100.0)
    new_h, new_w = max(1, int(round(h * frac))), max(1, int(round(w * frac)))
    y0, x0 = (h - new_h) // 2, (w - new_w) // 2
    cropped = img[y0:y0 + new_h, x0:x0 + new_w]
    return cv.resize(cropped, (w, h), interpolation=cv.INTER_LINEAR)


def _skew(img: np.ndarray, pct: float, _rng) -> np.ndarray:
    """Horizontal shear (skew_4/6/10), shear factor = pct/100."""
    h, w = img.shape[:2]
    shear = pct / 100.0
    matrix = np.array([[1, shear, -shear * h / 2.0], [0, 1, 0]], dtype=np.float32)
    return cv.warpAffine(img, matrix, (w, h), flags=cv.INTER_LINEAR,
                         borderMode=cv.BORDER_REFLECT_101)


def _perspective(img: np.ndarray, pct: float, _rng) -> np.ndarray:
    """Keystone perspective warp: top edge pulled in by pct% of width (persp_4/6/10)."""
    h, w = img.shape[:2]
    inset = (pct / 100.0) * w
    src = np.float32([[0, 0], [w - 1, 0], [w - 1, h - 1], [0, h - 1]])
    dst = np.float32([[inset, 0], [w - 1 - inset, 0], [w - 1, h - 1], [0, h - 1]])
    matrix = cv.getPerspectiveTransform(src, dst)
    return cv.warpPerspective(img, matrix, (w, h), flags=cv.INTER_LINEAR,
                              borderMode=cv.BORDER_REFLECT_101)


